"""Write a symbol list that lets one of our modules link against another.

usage: rel-exports.py MODULE.elf --id ID -o OUT.lst

Reads the module's linked (partially linked, relocatable) ELF and writes one
line per global symbol it defines, in the form elf2rel takes for symbols that
live in another REL module:

    ID,SECTION,OFFSET:name

elf2rel gives each REL section the index of the ELF section it came from
(one section-info entry per ELF section, in order), so SECTION is the
symbol's ELF section index and OFFSET its value, which is relative to that
section in a relocatable ELF. When the module is linked in the game, OSLinkFixed
resolves a reference against it through that module's section table, so it
works for .bss too (it points the empty section at the bss block).

A second module built with this list as an extra elf2rel symbol file calls
and reads the first one directly. The first must already be linked when the
second is; see docs/building.md.
"""
import argparse
import struct
import sys

sys.dont_write_bytecode = True

# Sections elf2rel copies into a REL (its section mask). Symbols elsewhere
# are not reachable at run time.
KEPT = (".init", ".text", ".ctors", ".dtors", ".rodata", ".data", ".bss")
# Entry points and linker tables every module has its own copy of.
SKIP = {"_prolog", "_epilog", "_unresolved", "_ctors", "_dtors", "__destroy_global_chain",
        "__register_global_object"}

SHT_SYMTAB = 2
SHT_NOBITS = 8
STB_GLOBAL = 1
STB_WEAK = 2
SHN_LORESERVE = 0xFF00


def kept(name):
    return any(name == k or name.startswith(k + ".") for k in KEPT)


def read_elf(path):
    data = open(path, "rb").read()
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 2:
        raise SystemExit(f"error: {path} is not a 32-bit big-endian ELF")
    (e_type,) = struct.unpack_from(">H", data, 16)
    if e_type != 1:
        raise SystemExit(f"error: {path} is not relocatable (type {e_type}); link it with -r1")
    e_shoff, = struct.unpack_from(">I", data, 0x20)
    e_shentsize, e_shnum, e_shstrndx = struct.unpack_from(">3H", data, 0x2E)
    sections = []
    for i in range(e_shnum):
        sections.append(struct.unpack_from(">10I", data, e_shoff + i * e_shentsize))
    names_off = sections[e_shstrndx][4]

    def cstr(offset):
        end = data.index(b"\0", offset)
        return data[offset:end].decode("ascii", "replace")

    named = [(cstr(names_off + s[0]), s) for s in sections]
    return data, named, cstr


def exports(path):
    data, sections, cstr = read_elf(path)
    nobits = [i for i, (name, s) in enumerate(sections) if kept(name) and s[1] == SHT_NOBITS and s[5]]
    if len(nobits) > 1:
        # OSLinkFixed gives the bss block to one empty section only (Brawl decompilation, OSLink.c:202-210).
        raise SystemExit(f"error: {path} has {len(nobits)} zero-filled sections; expected at most one")
    out = []
    for name, s in sections:
        if s[1] != SHT_SYMTAB:
            continue
        sh_offset, sh_size, sh_link, sh_entsize = s[4], s[5], s[6], s[9]
        strtab = sections[sh_link][1][4]
        for off in range(sh_offset, sh_offset + sh_size, sh_entsize):
            st_name, st_value, st_size, st_info, st_other, st_shndx = struct.unpack_from(">3I2BH", data, off)
            bind = st_info >> 4
            if bind not in (STB_GLOBAL, STB_WEAK) or st_shndx == 0 or st_shndx >= SHN_LORESERVE:
                continue
            sym = cstr(strtab + st_name)
            if not sym or sym in SKIP or not kept(sections[st_shndx][0]):
                continue
            out.append((st_shndx, st_value, sym))
    return sorted(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("elf")
    ap.add_argument("--id", type=int, required=True, help="REL module id of MODULE")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    syms = exports(a.elf)
    names = [s for _, _, s in syms]
    if len(set(names)) != len(names):
        raise SystemExit(f"error: {a.elf} defines a global symbol twice")
    with open(a.output, "w", newline="\n") as f:
        f.write(f"// Generated by scripts/rel-exports.py from {a.elf.replace(chr(92), '/')}; do not edit.\n")
        for shndx, value, sym in syms:
            f.write(f"{a.id},{shndx},{value:08X}:{sym}\n")
    print(f"exports {a.output}: {len(syms)} symbols of module {a.id}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
